"""Deterministic offline evaluations — no model calls, no holdout access.

Covers the two EVAL.md rows that need no live model: clustering quality against
NASA's own ``Events_Anomaly`` labels, and the Critic's catch rate on briefs
seeded with deliberately uncited claims. Both are reproducible from a seed, so
the numbers in the README can be regenerated by anyone with the dataset.
"""

from __future__ import annotations

import argparse
import json
import random
from collections.abc import Sequence
from datetime import UTC, datetime
from pathlib import Path

from agents.critic import strip_uncited_claims
from eval.metrics import adjusted_rand, cluster_purity
from pipeline.ingest import load_parquet
from pipeline.models import ASRSReport
from pipeline.risk import FrozenRiskPolicy

TRAIN_SPLIT = Path("data/raw/default/train/0000.parquet")
RUNS_DIR = Path("eval/runs")


def _labels(reports: Sequence[ASRSReport], policy: FrozenRiskPolicy) -> tuple[list[int], list[str]]:
    """Return per-report (cluster label, reference anomaly label).

    Reports whose coded ``Events_Anomaly`` is empty are dropped: with no ground
    truth they can neither raise nor lower purity, and keeping them would let a
    clustering look better simply by absorbing unlabeled rows.
    """
    from pipeline.cluster import cluster_reports

    clusters = cluster_reports(
        reports,
        min_cluster_size=int(policy.clustering.get("min_cluster_size", 5)),
        min_samples=int(policy.clustering.get("min_samples", 3)),
    )
    label_by_acn: dict[str, int] = {}
    for index, cluster in enumerate(clusters):
        for acn in cluster.member_acns:
            label_by_acn[acn] = -1 if cluster.noise else index
    cluster_labels: list[int] = []
    reference: list[str] = []
    for report in reports:
        if not report.anomaly_labels:
            continue
        cluster_labels.append(label_by_acn.get(report.acn, -1))
        # ASRS reports carry several semicolon-separated anomalies; the first is
        # the primary coded event and is what a single-label metric can score.
        reference.append(report.anomaly_labels[0])
    return cluster_labels, reference


def clustering_metrics(reports: Sequence[ASRSReport], policy: FrozenRiskPolicy) -> dict[str, float]:
    from collections import Counter

    cluster_labels, reference = _labels(reports, policy)
    assigned = [label for label in cluster_labels if label != -1]
    sizes = Counter(assigned)
    ordered_sizes = sorted(sizes.values())
    median_size = float(ordered_sizes[len(ordered_sizes) // 2]) if ordered_sizes else 0.0
    noise_fraction = (
        (len(cluster_labels) - len(assigned)) / len(cluster_labels) if cluster_labels else 0.0
    )
    # Purity is meaningless without the score a single undifferentiated blob
    # would get: on this slice the most common anomaly label alone is ~0.22, so
    # a purity of 0.30 is a modest gain, not a good absolute number.
    baseline_purity = (
        Counter(reference).most_common(1)[0][1] / len(reference) if reference else 0.0
    )
    return {
        "scored_reports": float(len(cluster_labels)),
        "cluster_count": float(len(sizes)),
        "median_cluster_size": median_size,
        "noise_fraction": noise_fraction,
        "purity_vs_events_anomaly": cluster_purity(cluster_labels, reference),
        "purity_majority_class_baseline": baseline_purity,
        "adjusted_rand_vs_events_anomaly": adjusted_rand(cluster_labels, reference),
        # EVAL.md predeclares noise < 0.40 as a reward-hacking tripwire, but
        # evaluate_guards is only ever invoked on the extractor promotion loop,
        # so nothing had ever checked it against the clustering stage. Surfaced
        # here rather than left for a reader to compute.
        "noise_fraction_guard_limit": 0.40,
        "noise_fraction_guard_passed": float(noise_fraction < 0.40),
    }


def critic_catch_rate(*, trials: int = 200, seed: int = 42) -> dict[str, float]:
    """Seed briefs with uncited claims and measure how many the gate removes.

    Three kinds of planted claim, because the gate has three distinct jobs:
    an uncited sentence, a sentence citing an ACN that exists in no report
    (fabricated provenance), and a correctly cited sentence that must SURVIVE —
    a gate that deletes everything would otherwise score a perfect catch rate.
    """
    rng = random.Random(seed)
    real = [str(1000000 + index) for index in range(50)]
    caught = planted = kept = legitimate = 0
    for _ in range(trials):
        acn = rng.choice(real)
        fabricated = str(rng.randint(9_000_000, 9_999_999))
        brief = "\n".join(
            [
                "# Draft",
                f"- A properly sourced observation. [ACN {acn}]",
                "- An unsourced assertion with no citation at all.",
                f"- An assertion citing a report that does not exist. [ACN {fabricated}]",
            ]
        )
        cleaned = strip_uncited_claims(brief, allowed_acns=real).cleaned_brief
        planted += 2
        caught += "An unsourced assertion" not in cleaned
        caught += f"[ACN {fabricated}]" not in cleaned
        legitimate += 1
        kept += f"[ACN {acn}]" in cleaned
    return {
        "seeded_claims": float(planted),
        "uncited_and_fabricated_catch_rate": caught / planted if planted else 0.0,
        "legitimate_claim_retention": kept / legitimate if legitimate else 0.0,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dataset", type=Path, default=TRAIN_SPLIT)
    parser.add_argument("--slice", type=int, default=5000)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args(argv)

    policy = FrozenRiskPolicy.from_path(Path("config/frozen.yaml"))
    reports = load_parquet(args.dataset)
    if args.slice < len(reports):
        reports = random.Random(args.seed).sample(reports, args.slice)

    report = {
        "recorded_at": datetime.now(UTC).isoformat(),
        "slice": args.slice,
        "seed": args.seed,
        "clustering": clustering_metrics(reports, policy),
        "critic": critic_catch_rate(seed=args.seed),
    }
    RUNS_DIR.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now(UTC).strftime("%Y%m%dT%H%M%SZ")
    (RUNS_DIR / f"{stamp}-offline.json").write_text(
        json.dumps(report, indent=2, sort_keys=True), encoding="utf-8"
    )
    print(json.dumps(report, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
